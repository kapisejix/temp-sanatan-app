async def seed_bhakti_content():
    """Main function to seed all bhakti content"""
    client = AsyncIOMotorClient(mongo_url)
    db = client[db_name]
    
    print("=" * 60)
    print("Starting Bhakti Content Seeding...")
    print("=" * 60)
    
    # Clear existing bhakti content (optional - comment out if you want to keep existing)
    # await db.bhakti_items.delete_many({})
    # await db.bhakti_verses.delete_many({})
    # print("Cleared existing bhakti content")
    
    total_items = 0
    total_verses = 0
    
    # Helper function to create bhakti item
    async def create_bhakti_item(category, item_data):
        nonlocal total_items, total_verses
        
        slug = item_data['title_en'].lower().replace(' ', '-').replace("'", "")
        slug = ''.join(c for c in slug if c.isalnum() or c == '-')
        
        # Check if already exists
        existing = await db.bhakti_items.find_one({"slug": slug, "category": category})
        if existing:
            print(f"  - Skipping (exists): {item_data['title_en']}")
            return
        
        doc = {
            "category": category,
            "subcategory": item_data.get('subcategory', ''),
            "slug": slug,
            "title_hi": item_data.get('title_hi', ''),
            "title_en": item_data.get('title_en', ''),
            "deity": item_data.get('deity', ''),
            "deity_hi": item_data.get('deity_hi', ''),
            "description_hi": item_data.get('description_hi', ''),
            "description_en": item_data.get('description_en', ''),
            "full_text": item_data.get('full_text', ''),
            "music_type": item_data.get('music_type', ''),
            "best_occasion": item_data.get('best_occasion', ''),
            "audio_url": "",
            "video_url": "",
            "thumbnail_url": "",
            "has_beginner_mode": category != 'aarti',
            "has_expert_mode": True,
            "total_verses": len(item_data.get('verses', [])),
            "sort_order": total_items + 1,
            "is_active": True,
            "is_premium": False,
            "tags": [item_data.get('deity', '').lower(), category],
            "supported_languages": ["hi", "en", "sa"],
            "audio_timestamps": [],
            "like_count": 0,
            "status": "published",
            "created_at": datetime.now(timezone.utc).isoformat(),
            "updated_at": datetime.now(timezone.utc).isoformat()
        }
        
        result = await db.bhakti_items.insert_one(doc)
        item_id = str(result.inserted_id)
        total_items += 1
        
        # Insert verses if provided
        verses = item_data.get('verses', [])
        for verse in verses:
            verse_doc = {
                "item_id": item_id,
                "verse_num": verse.get('verse_num', 1),
                "verse_type": verse.get('verse_type', 'shloka'),
                "sanskrit_text": verse.get('sanskrit_text', ''),
                "transliteration": verse.get('transliteration', ''),
                "meanings": verse.get('meanings', {}),
                "word_breakdown": verse.get('word_breakdown', []),
                "audio_start_ms": 0,
                "audio_end_ms": 0,
                "is_active": True
            }
            await db.bhakti_verses.insert_one(verse_doc)
            total_verses += 1
        
        print(f"  + Added: {item_data['title_en']} ({len(verses)} verses)")
    
    # Seed Aarti Content
    print("\n[1/10] Seeding Aarti Content...")
    for item in AARTI_CONTENT:
        await create_bhakti_item('aarti', item)
    
    # Seed Chalisa Content
    print("\n[2/10] Seeding Chalisa Content...")
    for item in CHALISA_CONTENT:
        await create_bhakti_item('chalisa', item)
    
    # Seed Namavali Content
    print("\n[3/10] Seeding Namavali Content...")
    for item in NAMAVALI_CONTENT:
        await create_bhakti_item('namavali', item)
    
    # Seed Sahasranama Content
    print("\n[4/10] Seeding Sahasranama Content...")
    for item in SAHASRANAMA_CONTENT:
        await create_bhakti_item('sahasranama', item)
    
    # Seed Vedic Mantra Content
    print("\n[5/10] Seeding Vedic Mantra Content...")
    for item in VEDIC_MANTRA_CONTENT:
        await create_bhakti_item('vedic_mantra', item)
    
    # Seed Stotram Content
    print("\n[6/10] Seeding Stotram Content...")
    for item in STOTRAM_CONTENT:
        await create_bhakti_item('stotram', item)
    
    # Seed Suktam Content
    print("\n[7/10] Seeding Suktam Content...")
    for item in SUKTAM_CONTENT:
        await create_bhakti_item('suktam', item)
    
    # Seed Ashtakam Content
    print("\n[8/10] Seeding Ashtakam Content...")
    for item in ASHTAKAM_CONTENT:
        await create_bhakti_item('ashtakam', item)
    
    # Seed Shatkam Content
    print("\n[9/10] Seeding Shatkam Content...")
    for item in SHATKAM_CONTENT:
        await create_bhakti_item('shatkam', item)
    
    # Seed Kavacham Content
    print("\n[10/10] Seeding Kavacham Content...")
    for item in KAVACHAM_CONTENT:
        await create_bhakti_item('kavacham', item)
    
    # Seed Nam Ramayanam Content
    print("\n[Bonus] Seeding Nam Ramayanam Content...")
    for item in NAM_RAMAYANAM_CONTENT:
        await create_bhakti_item('nam_ramayanam', item)
    
    # Create indexes
    await db.bhakti_items.create_index("category")
    await db.bhakti_items.create_index("subcategory")
    await db.bhakti_items.create_index("slug")
    await db.bhakti_items.create_index("status")
    await db.bhakti_verses.create_index("item_id")
    
    print("\n" + "=" * 60)
    print(f"Seeding Complete!")
    print(f"Total Items: {total_items}")
    print(f"Total Verses: {total_verses}")
    print("=" * 60)
    
    client.close()


if __name__ == "__main__":
    asyncio.run(seed_bhakti_content())
